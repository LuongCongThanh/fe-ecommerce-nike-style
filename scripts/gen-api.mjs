// Generates src/lib/api/generated/openapi.ts from the be-demo OpenAPI contract.
// The contract version is pinned here; CI regenerates and fails when the committed file differs.
// Override the source for local work with OPENAPI_URL=<url or path> pnpm gen:api.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const PINNED = 'https://github.com/LuongCongThanh/be-demo/releases/download/openapi-v0.5.0/openapi.json';
const OUTPUT = fileURLToPath(new URL('../src/lib/api/generated/openapi.ts', import.meta.url));
const HEADER = `/**
 * Generated by \`pnpm gen:api\` — do not edit by hand.
 * Source: the be-demo OpenAPI contract pinned in scripts/gen-api.mjs. Import only from src/lib/api.
 */
`;

const source = process.env.OPENAPI_URL ?? PINNED;
const url = /^[a-z]+:\/\//i.test(source) ? new URL(source) : new URL(source, `file://${process.cwd()}/`);
const ast = await openapiTS(url, { defaultNonNullable: false });
await writeFile(OUTPUT, HEADER + astToString(ast));
console.warn(`Generated ${OUTPUT} from ${source}`);
